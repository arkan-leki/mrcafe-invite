#!/usr/bin/env bash
# ===================================================================
#  دروستکەری بانگهێشتنامەی مستەر کافێ — سێرڤەری ناوخۆیی
#  ------------------------------------------------------------------
#  بۆچی پێویستە؟ وێبگەڕەکان ڕێگە نادەن کانواس وێنەیەک دەربکات کە لە
#  فایلێکی ناوخۆیی (file://) هاتووە. کاتێک پەڕەکە بە http:// کرایەوە،
#  داگرتنی وێنە بە تەواوی کار دەکات.
#
#  بەکارهێنان:
#      ./start.sh            # لەم فۆڵدەرە http://localhost:8000 دەکرێتەوە
#      ./start.sh 5500       # بە پۆرتی جیاواز
# ===================================================================
set -euo pipefail

cd "$(dirname "$0")"

PORT="${1:-8000}"
URL="http://localhost:${PORT}/"

if command -v python3 >/dev/null 2>&1; then
  SERVER=(python3 -m http.server "$PORT" --bind 127.0.0.1)
elif command -v python >/dev/null 2>&1; then
  SERVER=(python -m http.server "$PORT" --bind 127.0.0.1)
else
  echo "پێویستە python3 دابنرێت (یان هەر سێرڤەرێکی static)." >&2
  exit 1
fi

echo "──────────────────────────────────────────────"
echo " دروستکەری بانگهێشتنامە"
echo " ناونیشان: ${URL}"
echo " وەستان: Ctrl + C"
echo "──────────────────────────────────────────────"

# کردنەوەی وێبگەڕ دوای چرکەیەک (ئەگەر بەردەست بوو)
(
  sleep 1
  xdg-open "$URL" >/dev/null 2>&1 ||
    sensible-browser "$URL" >/dev/null 2>&1 ||
    echo "بە دەستی بکەرەوە: ${URL}"
) &

exec "${SERVER[@]}"
